# Initialize the project-local portable MySQL 8 instance (idempotent).
#
#   powershell -ExecutionPolicy Bypass -File scripts\mysql_init.ps1
#   powershell -ExecutionPolicy Bypass -File scripts\mysql_init.ps1 -Force   # wipe + re-init
#
# What it does:
#   1. extracts the official MySQL 8 zip into  <app>\.mysql\  (skipped when present);
#   2. writes  <app>\.mysql\my.ini  (127.0.0.1 only, port 3307, datadir runtime\mysql-data);
#   3. runs  mysqld --initialize-insecure  on first use;
#   4. starts mysqld, then calls scripts\mysql_bootstrap.py which creates
#      the ece@127.0.0.1 account (random password), ece_app / ece_original databases
#      and config\local\mysql.env.
# Nothing is registered as a system service and no system setting is changed.
[CmdletBinding()]
param(
    [switch]$Force,
    [int]$Port = 3307,
    [string]$ZipPath = ''
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'mysql_common.ps1')

$root = Get-EceRoot
$home2 = Get-EceMysqlHome
$dataDir = Get-EceDataDir
$logDir = Get-EceLogDir
$iniFile = Get-EceIniFile
$zip = $ZipPath
if (-not $zip) {
    $zip = Join-Path (Split-Path -Parent $root) '.tmp\mysql\mysql-8.0.28-winx64.zip'
}

function Write-Step([string]$text) { Write-Host "[mysql-init] $text" }

Write-Step "root      : $root"
Write-Step "mysql home: $home2"
Write-Step "data dir  : $dataDir"

# ---------------------------------------------------------------- 1. extract binaries
$mysqld = Join-Path $home2 'bin\mysqld.exe'
New-Item -ItemType Directory -Path (Split-Path -Parent $home2) -Force | Out-Null
if ($Force -and (Test-Path $home2)) {
    Write-Step 'removing existing .mysql directory (-Force)'
    Remove-Item -LiteralPath $home2 -Recurse -Force
}
if (-not (Test-Path $mysqld)) {
    if (-not (Test-Path $zip)) {
        throw "MySQL zip not found: $zip. Download it first or pass -ZipPath <zip>."
    }
    $size = (Get-Item -LiteralPath $zip).Length
    if ($size -lt 200MB) {
        throw "MySQL zip looks incomplete ($([Math]::Round($size / 1MB, 1)) MB < 200 MB): $zip"
    }
    $staging = Join-Path (Split-Path -Parent $root) '.tmp\mysql-extract'
    if (Test-Path $staging) { Remove-Item -LiteralPath $staging -Recurse -Force }
    New-Item -ItemType Directory -Path $staging -Force | Out-Null
    Write-Step "extracting $zip"
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [System.IO.Compression.ZipFile]::ExtractToDirectory($zip, $staging)
    $inner = Get-ChildItem -Path $staging -Directory | Select-Object -First 1
    if (-not $inner) { throw "Unexpected zip layout: no top-level directory in $staging" }
    Move-Item -LiteralPath $inner.FullName -Destination $home2
    Remove-Item -LiteralPath $staging -Recurse -Force -ErrorAction SilentlyContinue
    if (-not (Test-Path $mysqld)) { throw "Extraction failed: $mysqld not found" }
    Write-Step 'binaries ready'
} else {
    Write-Step 'binaries already installed (skip extraction)'
}

New-Item -ItemType Directory -Path $logDir -Force | Out-Null
New-Item -ItemType Directory -Path (Join-Path $root 'runtime\tmp\mysql') -Force | Out-Null
New-Item -ItemType Directory -Path (Split-Path -Parent $iniFile) -Force | Out-Null
New-Item -ItemType Directory -Path (Join-Path $root 'runtime') -Force | Out-Null

# ---------------------------------------------------------------- 2. my.ini
$n = '/'
$basedir = $home2.Replace('\', $n)
$datadirIni = $dataDir.Replace('\', $n)
$logIni = (Join-Path $logDir 'error.log').Replace('\', $n)
$ini = @"
# Portable project-local MySQL 8 instance - generated by scripts/mysql/mysql_init.ps1.
[mysqld]
basedir=$basedir
datadir=$datadirIni
port=$Port
bind-address=127.0.0.1
mysqlx=0
character-set-server=utf8mb4
collation-server=utf8mb4_0900_ai_ci
default_authentication_plugin=mysql_native_password
max_allowed_packet=256M
max_connections=64
innodb_buffer_pool_size=256M
log-error=$logIni
slow_query_log=0
pid-file=$((Join-Path $root 'runtime\tmp\mysql.pid').Replace('\', '/'))
tmpdir=$((Join-Path $root 'runtime\tmp\mysql').Replace('\', '/'))

[client]
host=127.0.0.1
port=$Port
default-character-set=utf8mb4
"@
# MySQL 8 on Windows reads option files in the system ANSI code page (UTF-8 makes the
# non-ASCII project path come out as '?'), so write my.ini as ANSI (GBK on zh-CN).
$ansi = 936
try {
    $codePage = [System.Globalization.CultureInfo]::CurrentCulture.TextInfo.ANSICodePage
    if ($codePage -gt 0) { $ansi = $codePage }
} catch { }
[System.IO.File]::WriteAllText($iniFile, $ini, [System.Text.Encoding]::GetEncoding($ansi))
Write-Step "my.ini written (ANSI cp$ansi): $iniFile"

# ---------------------------------------------------------------- 3. initialize datadir
$needsInit = -not (Test-Path (Join-Path $dataDir 'mysql'))
if ($Force -and (Test-Path $dataDir)) {
    Write-Step 'removing existing data directory (-Force)'
    Remove-Item -LiteralPath $dataDir -Recurse -Force
    $needsInit = $true
}
if ($needsInit) {
    New-Item -ItemType Directory -Path $dataDir -Force | Out-Null
    Write-Step 'mysqld --initialize-insecure (first run, ~30s)'
    Push-Location $home2
    try { cmd /d /c 'bin\mysqld.exe --defaults-file=..\..\config\local\mysql.ini --initialize-insecure --console' } finally { Pop-Location }
    if ($LASTEXITCODE -ne 0) {
        throw "mysqld --initialize-insecure failed (exit $LASTEXITCODE). Log:`n$(Get-EceErrorLogTail 40)"
    }
    Write-Step 'data directory initialized (root@localhost has an EMPTY password; local only)'
} else {
    Write-Step 'data directory already initialized (skip)'
}

# ---------------------------------------------------------------- 4. start + bootstrap
& (Join-Path $PSScriptRoot 'mysql_start.ps1') -Port $Port

$python = Find-EcePython
Write-Step 'provisioning account / databases / config\local\mysql.env'
& $python (Join-Path $PSScriptRoot 'mysql_bootstrap.py') --port $Port
if ($LASTEXITCODE -ne 0) {
    throw "mysql_bootstrap.py failed (exit $LASTEXITCODE)"
}

Write-Step 'done. config\local\mysql.env holds the local credentials (never commit it).'
Write-Step "next: python scripts\migrate_to_mysql.py   # import runtime\retail.sqlite3 -> ece_original"
