def execute_tool(name: str, params, batch) -> dict:
    """Run one declared tool.  Invalid tool params raise 400; runtime failures are ok=false."""
    if name not in TOOLS:
        raise BadRequest(f'未声明的工具：{name}')
    normalized = _VALIDATORS[name](params or {})
    started = time.monotonic()
    try:
        result = _HANDLERS[name](normalized, batch)
    except (DataError, ValueError) as exc:
        return {'name': name, 'params': normalized, 'ok': False, 'summary': f'工具执行失败：{exc}',
                'kind': TOOLS[name]['kind'], 'range': None, 'warnings': [], 'data': {},
                'elapsed_seconds': round(time.monotonic() - started, 3)}
    except BadRequest:
        raise
    except Exception:
        log.exception('AI tool %s failed', name)
        return {'name': name, 'params': normalized, 'ok': False,
                'summary': '工具执行失败：服务端内部错误（详见服务端日志）',
                'kind': TOOLS[name]['kind'], 'range': None, 'warnings': [], 'data': {},
                'elapsed_seconds': round(time.monotonic() - started, 3)}
    result = dict(result)
    result.update({'name': name, 'params': normalized, 'ok': True,
                   'summary': _redact(result.get('summary') or ''),
                   'elapsed_seconds': round(time.monotonic() - started, 3)})
    return result


