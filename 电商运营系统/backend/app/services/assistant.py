def _local_answer(plan: dict, results: list[dict], range_: dict, batch) -> str:
    lines = ['未调用大模型，数字来自服务端工具。']
    for result in results:
        if result.get('ok'):
            lines.append(f"· {result['summary']}")
        else:
            lines.append(f"· 工具 {result['name']} 执行失败：{result['summary']}")
    if range_.get('start'):
        lines.append(f"范围：{range_['start']}~{range_.get('end') or range_['start']}"
                     + (f"，商品 {range_['product']}" if range_.get('product') else '')
                     + (f"，国家 {range_['country']}" if range_.get('country') else '')
                     + f"；数据批次：{batch['id']}（{batch['label']}）。")
    else:
        lines.append(f"数据批次：{batch['id']}（{batch['label']}）。")
    if range_.get('start') and range_.get('start') < (_manifest(batch).get('date_min') or '0000-00-00'):
        lines.append('提示：查询区间超出数据覆盖范围的部分按无记录显示，不代表市场为零。')
    if range_.get('end') and range_.get('end') > (_manifest(batch).get('date_max') or '9999-99-99'):
        lines.append('提示：查询区间超出数据覆盖范围的部分按无记录显示。')
    lines.append('口径提示：历史实际是数据中已发生的交易；预测为模型结果且有误差；'
                 '模拟库存不是真实库存；数据没有成本字段，销售额不等于利润。')
    return '\n'.join(lines)


def _llm_compact(results: list[dict]) -> str:
    payload = []
    for result in results:
        data = result.get('data') or {}
        slim = {k: v for k, v in data.items() if k not in ('lines', 'rows')}
        if data.get('rows'):
            slim['rows_head'] = data['rows'][:10]
            slim['rows_count'] = len(data['rows'])
        if data.get('ranking'):
            slim['ranking'] = data['ranking'][:10]
        if data.get('countries'):
            slim['countries'] = data['countries'][:10]
        payload.append({'name': result['name'], 'ok': result['ok'],
                        'params': result['params'], 'summary': result['summary'],
                        'data': slim})
    text = json.dumps(payload, ensure_ascii=False, default=str)
    return text[:8000]


