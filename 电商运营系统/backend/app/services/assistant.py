def _params_dashboard(raw) -> dict:
    if not isinstance(raw, dict):
        raise BadRequest('工具参数必须为对象')
    out = {}
    for key in ('start', 'end'):
        if raw.get(key) not in (None, ''):
            out[key] = _date_param(raw[key], key)
    for key in ('product', 'country'):
        if raw.get(key) not in (None, ''):
            out[key] = _text_param(raw[key], key, 80 if key == 'product' else 64)
    if out.get('start') and out.get('end') and out['start'] > out['end']:
        raise BadRequest('开始日期不能晚于结束日期')
    return out


def _params_product_search(raw) -> dict:
    if not isinstance(raw, dict):
        raise BadRequest('工具参数必须为对象')
    q = _text_param(raw.get('q'), 'q', 100)
    if len(q) < 1:
        raise BadRequest('商品检索关键字不能为空')
    return {'q': q}


def _params_ranking(raw) -> dict:
    out = _params_dashboard(raw)
    top_n = raw.get('top_n', 10)
    try:
        top_n = int(top_n)
    except (TypeError, ValueError):
        raise BadRequest('top_n 必须是整数') from None
    if not 1 <= top_n <= 50:
        raise BadRequest('top_n 必须在 1 到 50 之间')
    out['top_n'] = top_n
    return out


def _params_orders(raw) -> dict:
    out = _params_dashboard(raw)
    for key, default, low, high in (('page', 1, 1, 1000), ('page_size', 10, 1, 100)):
        value = raw.get(key, default)
        try:
            value = int(value)
        except (TypeError, ValueError):
            raise BadRequest(f'{key} 必须是整数') from None
        if not low <= value <= high:
            raise BadRequest(f'{key} 必须在 {low} 到 {high} 之间')
        out[key] = value
    if raw.get('order_key') not in (None, ''):
        order_key = _text_param(raw['order_key'], 'order_key', 20)
        if not re.fullmatch(r'[0-9A-Za-z\-]{1,20}', order_key):
            raise BadRequest('order_key 格式无效')
        out['order_key'] = order_key
    return out


def _params_forecast(raw) -> dict:
    if not isinstance(raw, dict):
        raise BadRequest('工具参数必须为对象')
    out = {}
    if raw.get('origin') not in (None, ''):
        out['origin'] = _date_param(raw['origin'], 'origin')
    if raw.get('model') not in (None, ''):
        model = _text_param(raw['model'], 'model', 40)
        if model != ACTIVE_MODEL:
            raise BadRequest('系统统一使用销量预测模型，无需选择其他模型')
    return out


