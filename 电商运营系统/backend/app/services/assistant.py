# --------------------------------------------------------------------------- helpers
def _redact(value):
    """Remove the configured API key from anything that can reach a response/log."""
    if not isinstance(value, str):
        return value
    key = config.AI_API_KEY
    if key and len(key) >= 4:
        value = value.replace(key, '***')
    return re.sub(r'sk-[A-Za-z0-9_\-]{6,}', '***', value)


def ai_config() -> dict:
    """Effective AI configuration: environment defaults + non-secret ``settings.ai`` overrides.

    The API key is read from the environment only (never from the settings table); the
    overrides can only change base_url/model/timeout, so a page-side setting cannot leak
    or inject a secret.
    """
    overrides = {}
    try:
        stored = db.get_setting('ai')
        if isinstance(stored, dict):
            overrides = {k: v for k, v in stored.items() if v not in (None, '')}
    except Exception:  # missing table / corrupt value must not break the AI endpoints
        log.exception('failed to read settings.ai override')
    base_url = str(overrides.get('base_url') or config.AI_BASE_URL or '').strip()
    model = str(overrides.get('model') or config.AI_MODEL or '').strip()
    try:
        timeout = float(overrides.get('timeout_seconds') or config.AI_TIMEOUT_SECONDS)
    except (TypeError, ValueError):
        timeout = config.AI_TIMEOUT_SECONDS
    if not 1 <= timeout <= 600:
        timeout = config.AI_TIMEOUT_SECONDS
    api_key = config.AI_API_KEY
    return {
        'base_url': base_url,
        'model': model,
        'timeout_seconds': timeout,
        'key_present': bool(api_key),
        'configured': bool(base_url and api_key and model),
    }


def _date_param(value, field: str) -> str:
    if not isinstance(value, str):
        raise BadRequest(f'{field} 必须是 YYYY-MM-DD 字符串')
    value = value.strip()
    if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', value):
        raise BadRequest(f'{field} 格式必须为 YYYY-MM-DD')
    try:
        date.fromisoformat(value)
    except ValueError:
        raise BadRequest(f'{field} 不是有效日期') from None
    return value


def _text_param(value, field: str, limit: int) -> str:
    if not isinstance(value, str):
        raise BadRequest(f'{field} 必须是字符串')
    value = value.strip()
    if len(value) > limit:
        raise BadRequest(f'{field} 过长（最多{limit}字符）')
    return value


def validate_scope(scope) -> dict:
    """Validate an optional ``scope`` object; raise 400 for malformed values."""
    out = {'start': None, 'end': None, 'product': '', 'country': '', 'scenario_id': None}
    if scope is None:
        return out
    if not isinstance(scope, dict):
        raise BadRequest('scope 必须为 JSON 对象')
    unknown = set(scope) - set(out)
    if unknown:
        raise BadRequest('scope 含未知字段：' + '、'.join(sorted(unknown)))
    if scope.get('start') is not None:
        out['start'] = _date_param(scope['start'], 'scope.start')
    if scope.get('end') is not None:
        out['end'] = _date_param(scope['end'], 'scope.end')
    if out['start'] and out['end']:
        if out['start'] > out['end']:
            raise BadRequest('开始日期不能晚于结束日期')
        if (date.fromisoformat(out['end']) - date.fromisoformat(out['start'])).days > MAX_RANGE_DAYS:
            raise BadRequest('单次查询最多覆盖4年')
    if scope.get('product') is not None:
        out['product'] = _text_param(scope['product'], 'scope.product', 80)
    if scope.get('country') is not None:
        out['country'] = _text_param(scope['country'], 'scope.country', 64)
    if scope.get('scenario_id') is not None:
        value = _text_param(scope['scenario_id'], 'scope.scenario_id', 64)
        if value and not re.fullmatch(r'[A-Za-z0-9_\-]{1,64}', value):
            raise BadRequest('scope.scenario_id 只能包含字母、数字、下划线和短横线')
        out['scenario_id'] = value or None
    return out


def _manifest(batch) -> dict:
    return batch.get('manifest') or {}


def scope_for_batch(scope: dict, batch) -> dict:
    """Cross-check an explicit scope against the current batch (400 on impossible filters)."""
    resolved = dict(scope)
    country = (resolved.get('country') or '').strip()
    if country:
        resolved['country'] = COUNTRY_CN.get(country, country)
    meta = _manifest(batch)
    date_min, date_max = meta.get('date_min'), meta.get('date_max')
    start, end = resolved.get('start'), resolved.get('end')
    if start and not end and date_max and start > date_max:
        raise BadRequest(f'开始日期晚于数据覆盖末日 {date_max}，请调整 scope.start')
    if end and not start and date_min and end < date_min:
        raise BadRequest(f'结束日期早于数据覆盖起始日 {date_min}，请调整 scope.end')
    if start and end and (end < date_min or start > date_max):
        raise BadRequest(f'日期范围与数据覆盖范围 {date_min}~{date_max} 没有交集')
    if resolved.get('product'):
        _assert_product_exists(batch, resolved['product'])
    if resolved.get('country'):
        countries = _countries(batch)
        if countries and resolved['country'] not in countries:
            raise BadRequest(f"国家 {resolved['country']} 不在当前批次的国家列表中")
    return resolved


def default_range(batch) -> dict:
    meta = _manifest(batch)
    end = meta.get('date_max') or date.today().isoformat()
    start = max(meta.get('date_min') or end, (date.fromisoformat(end) - timedelta(days=DEFAULT_WINDOW_DAYS - 1)).isoformat())
    return {'start': start, 'end': end, 'product': '', 'country': ''}


def _countries(batch) -> list[str]:
    key = batch['id']
    with COUNTRY_CACHE_LOCK:
        cached = COUNTRY_CACHE.get(key)
    if cached is not None:
        return cached
    store = store_for(batch)
    with store.connect() as cx:
        rows = [r[0] for r in cx.execute("select distinct country from transactions where sale=1 and country<>''")]
    rows.sort()
    with COUNTRY_CACHE_LOCK:
        COUNTRY_CACHE[key] = rows
    return rows


def _forecast_cached(batch, params: dict) -> dict:
    key = (batch['id'], params.get('origin') or '', ACTIVE_MODEL)
    with FORECAST_CACHE_LOCK:
        cached = FORECAST_CACHE.get(key)
    if cached is not None:
        return cached
    store = store_for(batch)
    series = store.series()
    result = forecast(series, origin=params.get('origin'), model=ACTIVE_MODEL)
    with FORECAST_CACHE_LOCK:
        FORECAST_CACHE[key] = result
    return result


