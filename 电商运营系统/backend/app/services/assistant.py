def _strip_dates(text: str) -> str:
    text = _DATE_RANGE_RE.sub(' ', text)
    text = _DATE_SINGLE_RE.sub(' ', text)
    return text


def _parse_question_dates(question: str, batch) -> tuple[str | None, str | None, str | None]:
    """Return ``(start, end, note)`` parsed from natural language; note explains the source."""
    meta = _manifest(batch)
    date_max = meta.get('date_max')
    date_min = meta.get('date_min')
    match = _DATE_RANGE_RE.search(question)
    if match:
        start = f'{int(match.group(1)):04d}-{int(match.group(2)):02d}-{int(match.group(3)):02d}'
        end = f'{int(match.group(4)):04d}-{int(match.group(5)):02d}-{int(match.group(6)):02d}'
        if start > end:
            return start, end, '倒序日期'
        if (date.fromisoformat(end) - date.fromisoformat(start)).days > MAX_RANGE_DAYS:
            return start, end, '超4年'
        return start, end, 'explicit'
    match = _DATE_SINGLE_RE.search(question)
    if match:
        day = f'{int(match.group(1)):04d}-{int(match.group(2)):02d}-{int(match.group(3)):02d}'
        return day, day, 'explicit'
    match = _RELATIVE_RE.search(question)
    if match and date_max:
        days = int(match.group(1))
        if days < 1:
            return None, None, 'bad-relative'
        if days > MAX_RANGE_DAYS:
            return None, None, '超4年'
        start = (date.fromisoformat(date_max) - timedelta(days=days - 1)).isoformat()
        return max(start, date_min or start), date_max, 'relative'
    if '上个月' in question or '上月' in question:
        anchor = date.fromisoformat(date_max)
        last_day_prev = anchor.replace(day=1) - timedelta(days=1)
        return last_day_prev.replace(day=1).isoformat(), last_day_prev.isoformat(), 'month'
    if '本月' in question or '这个月' in question:
        anchor = date.fromisoformat(date_max)
        return anchor.replace(day=1).isoformat(), date_max, 'month'
    return None, None, None


def _parse_forecast_origin(question: str) -> str | None:
    """An explicit date inside a forecast question becomes the forecast origin."""
    match = _DATE_SINGLE_RE.search(question)
    if not match:
        return None
    return f'{int(match.group(1)):04d}-{int(match.group(2)):02d}-{int(match.group(3)):02d}'


def _parse_country(question: str, batch) -> str | None:
    for cn, en in COUNTRY_CN.items():
        if cn in question:
            return en
    lowered = question.lower()
    try:
        countries = _countries(batch)
    except Exception:  # pragma: no cover - defensive; metadata tools still work
        log.exception('country list unavailable')
        countries = []
    for country in sorted(countries, key=len, reverse=True):
        if country.lower() in lowered:
            return country
    return None


def _clean_terms(text: str) -> str:
    for term in CN_STOP_SORTED:
        text = text.replace(term, ' ')
    return text


def _extract_product_term(question: str) -> str | None:
    """Best-effort product reference: quoted text, stock code, English name or 商品X."""
    stripped = _strip_dates(question)
    match = _QUOTED_RE.search(stripped)
    if match:
        return match.group(1).strip()
    match = _CODE_RE.search(stripped)
    if match:
        return match.group(1)
    if any(word in stripped for word in PLACEHOLDER_PRODUCTS):
        return None
    match = _MARKER_TERM_RE.search(stripped)
    if match:
        term = match.group(1).strip()
        if term and re.search(r'[\u4e00-\u9fff]', term):
            cleaned = _clean_terms(term)
            cjk = re.findall(r'[\u4e00-\u9fff]{2,12}', cleaned)
            if cjk:
                return cjk[0]
    english = []
    for chunk in _EN_TERM_RE.findall(stripped):
        cleaned = re.sub(r'\b(top|forecast|brief|invoice|order|orders|sales|sale|cost|profit|sku)\b', ' ', chunk,
                         flags=re.IGNORECASE)
        cleaned = re.sub(r'\s+', ' ', cleaned).strip(' .,&-')
        if len(cleaned) >= 2:
            english.append(cleaned)
    if english:
        return max(english, key=len)
    marker = any(word in question for word in ('商品', '产品', '货号', 'SKU'))
    if marker:
        residual = _clean_terms(stripped)
        cjk = re.findall(r'[\u4e00-\u9fff]{2,12}', residual)
        if cjk:
            return cjk[0]
    return None


def _lookup_product(store, term: str) -> tuple[dict | None, str | None]:
    """Resolve a term to exactly one product or explain why it cannot."""
    with store.connect() as cx:
        if _CODE_RE.fullmatch(term):
            row = cx.execute(
                'select stock_code, max(description) name, coalesce(sum(quantity),0) quantity '
                'from transactions where sale=1 and stock_code=? group by stock_code', (term,)).fetchone()
            if row:
                return dict(row), None
            row = cx.execute(
                'select stock_code, max(description) name, coalesce(sum(quantity),0) quantity '
                'from transactions where sale=1 and upper(stock_code)=upper(?) '
                'group by stock_code order by quantity desc limit 1', (term,)).fetchone()
            if row:
                return dict(row), None
            return None, f'没有找到商品编号「{term}」，请确认编号是否正确（例如 85123A）。'
    analytics = Analytics(store)
    rows = analytics.search_products(term)
    if not rows:
        return None, (f'没有找到与「{term}」匹配的商品，请提供商品编号（如 85123A）'
                      '或更完整的英文商品名称。')
    exact = [r for r in rows if (r.get('name') or '').strip().upper() == term.strip().upper()]
    if exact:
        return max(exact, key=lambda r: r['quantity']), None
    if len(rows) == 1:
        return rows[0], None
    candidates = '；'.join(f"{r['stock_code']}（{r['name']}，累计销量{r['quantity']:,}）" for r in rows[:5])
    return None, (f'「{term}」匹配到多个商品，请指定商品编号：{candidates}'
                  + ('…' if len(rows) > 5 else ''))


def _question_without_country(question: str, country: str | None) -> str:
    if not country:
        return question
    text = question.replace(country, ' ')
    for cn, en in COUNTRY_CN.items():
        if en == country:
            text = text.replace(cn, ' ')
    return text


def plan_question(question: str, scope: dict, batch) -> dict:
    """Deterministic local rule planner: map the question onto declared tools.

    Returns ``{'tools': [...], 'clarification': str|None, 'intent': str,
    'range': dict|None, 'warnings': [...]}``.
    """
    q = question.strip()
    plan = {'tools': [], 'clarification': None, 'intent': '', 'range': None, 'warnings': []}
    meta = _manifest(batch)
    start, end, date_note = _parse_question_dates(q, batch)
    if date_note == '倒序日期':
        plan.update(intent='clarify-date-order',
                    clarification=f'开始日期 {start} 晚于结束日期 {end}，请确认要查询的日期范围。')
        return plan
    if date_note == '超4年':
        plan.update(intent='clarify-range',
                    clarification='单次查询最多覆盖4年，请缩小日期范围（例如按月或按季度查询）。')
        return plan
    if date_note == 'bad-relative':
        plan.update(intent='clarify-range', clarification='“最近N天”的天数必须是正整数。')
        return plan
    country = _parse_country(q, batch) or (scope.get('country') or None)
    product_term = _extract_product_term(_question_without_country(q, country))

    base = {}
    if start:
        base['start'], base['end'] = start, end
    elif scope.get('start'):
        base['start'] = scope['start']
        base['end'] = scope.get('end') or meta.get('date_max')
    if country:
        base['country'] = country

    def _scope_product():
        if scope.get('product'):
            return scope['product'], None, []
        return None, None, []

    if any(word in q for word in PROFIT_WORDS):
        plan.update(intent='clarify-cost',
                    clarification=('当前数据没有成本/采购价字段，无法计算利润或毛利；'
                                   '可以改为查询销售额、销量或订单数，不能用销售额代替利润。'))
        return plan
    if any(word in q for word in COMPARE_WORDS) and not _DATE_RANGE_RE.search(q) and not _RELATIVE_RE.search(q):
        plan.update(intent='clarify-compare',
                    clarification='请说明要对比的两个时间段（例如“2011-11-01到2011-11-30 与 2011-10-01到2011-10-31 比较”）。')
        return plan
    if any(word in q for word in BRIEF_WORDS) and not any(word in q for word in SALES_WORDS + RANKING_WORDS):
        plan.update(intent='clarify-brief',
                    clarification=('运营简报请调用 POST /api/ai/brief 生成，并用 GET /api/ai/briefs/{id}.md 下载；'
                                   '简报由确定性模板生成（provider=template）。'))
        return plan

    # inventory ------------------------------------------------------------
    if any(word in q for word in INVENTORY_WORDS) or '库存' in q:
        tools = []
        code = None
        alias = None
        if product_term and product_term in PLACEHOLDER_PRODUCTS:
            product_term = None
        if product_term:
            resolved, error = _lookup_product(store_for(batch), product_term)
            tools.append({'name': 'product_search', 'params': {'q': product_term}})
            if error:
                plan.update(intent='clarify-product', clarification=error, tools=tools)
                return plan
            code = resolved['stock_code']
            alias = resolved.get('name')
        scope_code, scope_error, _ = _scope_product()
        if not code and scope_code:
            code = scope_code
        if not code:
            plan.update(intent='clarify-inventory-product',
                        clarification=('查询模拟库存需要商品编号，请说明要查哪个商品（例如“85123A 库存”）。'
                                       '模拟库存结论不代表真实库存。'), tools=tools)
            return plan
        params = {'stock_code': code}
        scenario_id = scope.get('scenario_id')
        if scenario_id:
            params['scenario_id'] = scenario_id
        tools.append({'name': 'inventory_query', 'params': params})
        plan.update(intent='inventory', tools=tools,
                    range={'start': None, 'end': None, 'product': code, 'country': ''})
        return plan

    # forecast -------------------------------------------------------------
    if any(word in q for word in FORECAST_WORDS):
        match = _FUTURE_DAYS_RE.search(q)
        if match and int(match.group(1)) != FORECAST_HORIZON:
            plan.update(intent='clarify-forecast-horizon',
                        clarification=f'现有预测服务只支持未来{FORECAST_HORIZON}天的全店预测，'
                                      f'不支持未来{match.group(1)}天；请改为“未来7天全店预测”。')
            return plan
        if any(word in q for word in PLACEHOLDER_PRODUCTS):
            plan.update(intent='clarify-forecast-scope',
                        clarification=('现有预测模型只支持“全店未来7天”预测，不支持按商品预测；'
                                       '请提供具体全店预测需求，或改为查询某个商品的历史销量。'))
            return plan
        if product_term or country or scope.get('product') or scope.get('country'):
            plan.update(intent='clarify-forecast-scope',
                        clarification=('现有预测模型只支持“全店未来7天”预测，不支持按商品或国家预测；'
                                       '可以改为查询该商品/国家的历史销量，或查看全店未来7天预测。'))
            return plan
        params = {}
        origin = _parse_forecast_origin(q)
        if origin:
            params['origin'] = origin
        plan.update(intent='forecast', tools=[{'name': 'forecast_7d', 'params': params}])
        return plan

    # batch / data source --------------------------------------------------
    if any(word in q for word in BATCH_WORDS) and not any(word in q for word in SALES_WORDS + RANKING_WORDS + ORDER_WORDS):
        plan.update(intent='batch', tools=[{'name': 'batch_info', 'params': {}}])
        return plan

    # ranking --------------------------------------------------------------
    if (any(word in q for word in RANKING_WORDS) or _RANKING_RE.search(q)) \
            and not any(word in q for word in ORDER_WORDS):
        params = dict(base)
        top_match = _TOP_N_RE.search(q)
        if top_match:
            params['top_n'] = max(1, min(50, int(top_match.group(1))))
        tools = []
        if product_term:
            resolved, error = _lookup_product(store_for(batch), product_term)
            tools.append({'name': 'product_search', 'params': {'q': product_term}})
            if error:
                plan.update(intent='clarify-product', clarification=error, tools=tools)
                return plan
            params['product'] = resolved['stock_code']
        tools.append({'name': 'product_ranking', 'params': params})
        plan.update(intent='ranking', tools=tools)
        return plan

    # orders / transactions ------------------------------------------------
    if any(word in q for word in ORDER_WORDS):
        params = dict(base)
        order_match = _ORDER_KEY_RE.search(_strip_dates(q))
        if order_match:
            params['order_key'] = order_match.group(1)
        size_match = _PAGE_N_RE.search(q)
        if size_match:
            params['page_size'] = max(1, min(100, int(size_match.group(1))))
        tools = []
        if product_term and not order_match:
            resolved, error = _lookup_product(store_for(batch), product_term)
            tools.append({'name': 'product_search', 'params': {'q': product_term}})
            if error:
                plan.update(intent='clarify-product', clarification=error, tools=tools)
                return plan
            params['product'] = resolved['stock_code']
        tools.append({'name': 'orders_query', 'params': params})
        plan.update(intent='orders', tools=tools)
        return plan

    # product search -------------------------------------------------------
    if any(word in q for word in SEARCH_WORDS):
        if not product_term:
            plan.update(intent='clarify-search',
                        clarification='请提供要检索的商品编号或名称关键字（例如“搜索 PAPER CRAFT”）。')
            return plan
        plan.update(intent='product_search', tools=[{'name': 'product_search', 'params': {'q': product_term}}])
        return plan

    # dashboard / sales ----------------------------------------------------
    if any(word in q for word in SALES_WORDS):
        params = dict(base)
        tools = []
        if product_term and product_term not in PLACEHOLDER_PRODUCTS:
            resolved, error = _lookup_product(store_for(batch), product_term)
            tools.append({'name': 'product_search', 'params': {'q': product_term}})
            if error:
                plan.update(intent='clarify-product', clarification=error, tools=tools)
                return plan
            params['product'] = resolved['stock_code']
        tools.append({'name': 'dashboard_summary', 'params': params})
        plan.update(intent='dashboard', tools=tools)
        return plan

    plan.update(intent='clarify-unsupported',
                clarification=('我只做本系统的只读数据问答：可按日期/商品/国家查询销量、销售额、订单数，'
                               '商品检索，订单查询，全店未来7天预测，模拟库存查询和数据批次信息。'
                               '请补充查询对象和日期范围（例如“2011-11-10到2011-12-09全店卖了多少”）。'))
    return plan


