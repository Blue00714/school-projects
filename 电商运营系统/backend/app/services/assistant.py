def inventory_overview(limit: int = 5, scenario_id: str | None = None) -> dict:
    """Read-only simulated-inventory overview used by the deterministic brief."""
    module, reason = _inventory_service()
    if module is not None:
        try:
            scenarios = module.list_scenarios()
            scenario = None
            if scenario_id:
                scenario = next((s for s in scenarios if s['id'] == scenario_id), None)
                if not scenario:
                    return {'simulated': True, 'service_module_ready': True, 'scenarios': scenarios,
                            'scenario': None, 'items': [], 'candidates': [],
                            'error': f'模拟库存场景 {scenario_id} 不存在'}
            elif scenarios:
                scenario = dict(scenarios[0])
            if not scenario:
                return {'simulated': True, 'service_module_ready': True, 'scenarios': [],
                        'scenario': None, 'items': [], 'candidates': []}
            payload = module.items_payload(scenario['id'])
            items = [_normalize_inventory_item(row) for row in (payload.get('items') or [])]
            candidates = sorted(items, key=lambda x: x['replenishment_candidate'], reverse=True)[:limit]
            return {'simulated': True, 'service_module_ready': True, 'scenarios': scenarios,
                    'scenario': scenario, 'items': items, 'candidates': candidates}
        except Exception:  # service bug/partial implementation: degrade to read-only tables
            log.exception('inventory overview via service failed; falling back to tables')
    with db.connect() as cx:
        scenarios = [dict(r) for r in cx.execute(
            'select id,name,note,created_at from inventory_scenarios order by created_at desc')]
        if scenario_id:
            scenario = next((row for row in scenarios if row['id'] == scenario_id), None)
            if not scenario:
                return {'simulated': True, 'service_module_ready': module is not None,
                        'scenarios': scenarios, 'scenario': None, 'items': [], 'candidates': [],
                        'error': f'模拟库存场景 {scenario_id} 不存在'}
        elif scenarios:
            scenario = scenarios[0]
        else:
            return {'simulated': True, 'service_module_ready': module is not None, 'scenarios': [],
                    'scenario': None, 'items': [], 'candidates': []}
        item_rows = [dict(r) for r in cx.execute(
            'select * from inventory_items where scenario_id=?', (scenario['id'],))]
        items = []
        for item in item_rows:
            snapshot = _inventory_balance(cx, scenario['id'], item['stock_code'])
            if snapshot:
                items.append(snapshot)
        candidates = sorted(items, key=lambda x: x['replenishment_candidate'], reverse=True)[:limit]
    return {'simulated': True, 'service_module_ready': module is not None, 'scenarios': scenarios,
            'scenario': scenario, 'items': items, 'candidates': candidates}
