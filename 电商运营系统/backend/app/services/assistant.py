    if not isinstance(raw, dict):
        raise BadRequest('工具参数必须为对象')
    code = _text_param(raw.get('stock_code'), 'stock_code', 40)
    if not code:
        raise BadRequest('stock_code 不能为空')
    out = {'stock_code': code}
    if raw.get('scenario_id') not in (None, ''):
        scenario_id = _text_param(raw['scenario_id'], 'scenario_id', 64)
        if not re.fullmatch(r'[A-Za-z0-9_\-]{1,64}', scenario_id):
            raise BadRequest('scenario_id 格式无效')
        out['scenario_id'] = scenario_id
    return out


