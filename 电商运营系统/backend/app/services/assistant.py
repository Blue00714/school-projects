def _inventory_service():
    """Tolerant import of the parallel inventory service module (never raises).

    The inventory module is developed by another teammate; when it is not importable the
    tool must degrade to a clear message instead of a 500.  When it is available its
    public read-only functions are the source of truth; a read-only table query with the
    same contract formula is kept as a fallback.
    """
    try:
        from app.services import inventory as module
        return module, ''
    except Exception as exc:  # missing module, import error, partial implementation
        return None, f'{type(exc).__name__}: {exc}'[:200]


def _normalize_inventory_item(item: dict) -> dict:
    lead = int(item.get('lead_time_days') or 0)
    daily = float(item.get('daily_demand') or 0)
    effective = item.get('in_transit_effective', item.get('effective_in_transit', 0)) or 0
    return {
        'stock_code': item.get('stock_code'), 'name': item.get('name') or '',
        'initial_qty': float(item.get('initial_qty') or 0), 'lead_time_days': lead,
        'safety_stock': float(item.get('safety_stock') or 0), 'daily_demand': daily,
        'balance': float(item.get('balance') or 0),
        'effective_in_transit': float(effective), 'in_transit_total': float(item.get('in_transit_total') or 0),
        'lead_time_demand': lead * daily,
        'replenishment_candidate': float(item.get('replenishment_candidate') or 0),
        'horizon_date': (date.today() + timedelta(days=lead)).isoformat(),
    }


def _inventory_via_service(module, params) -> tuple[dict, list[dict], dict]:
    scenarios = module.list_scenarios()
    scenario = None
    if params.get('scenario_id'):
        scenario = next((s for s in scenarios if s['id'] == params['scenario_id']), None)
        if not scenario:
            raise ValueError(f"模拟库存场景 {params['scenario_id']} 不存在")
    elif scenarios:
        scenario = scenarios[0]
    if not scenario:
        raise ValueError('尚未建立任何模拟库存场景（模拟库存不是真实库存，请先在“模拟库存”页创建场景）')
    payload = module.items_payload(scenario['id'])
    items = payload.get('items') or []
    wanted = str(params['stock_code']).upper()
    item = next((row for row in items if str(row.get('stock_code', '')).upper() == wanted), None)
    if not item:
        raise ValueError(f"模拟库存场景 {scenario['name']} 中没有商品 {params['stock_code']} 的模拟参数")
    normalized = [_normalize_inventory_item(row) for row in items]
    current = next(row for row in normalized if str(row['stock_code']).upper() == wanted)
    return dict(scenario, item_count=int(scenario.get('item_count') or len(items))), normalized, current


def _inventory_balance(cx, scenario_id: str, stock_code: str) -> dict | None:
    item = cx.execute(
        'select * from inventory_items where scenario_id=? and upper(stock_code)=upper(?)',
        (scenario_id, stock_code)).fetchone()
    if not item:
        return None
    item = dict(item)
    moved = cx.execute(
        "select coalesce(sum(case when kind='in' then qty else -qty end),0) as delta "
        'from inventory_movements where scenario_id=? and stock_code=?',
        (scenario_id, item['stock_code'])).fetchone()[0]
    balance = float(item['initial_qty']) + float(moved or 0)
    lead = int(item['lead_time_days'])
    horizon = (date.today() + timedelta(days=lead)).isoformat()
    effective = cx.execute(
        "select coalesce(sum(qty),0) from inventory_in_transit "
        "where scenario_id=? and stock_code=? and status='in_transit' and expected_date<=?",
        (scenario_id, item['stock_code'], horizon)).fetchone()[0]
    lead_demand = lead * float(item['daily_demand'])
    candidate = max(0.0, lead_demand + float(item['safety_stock']) - balance - float(effective or 0))
    return {
        'stock_code': item['stock_code'], 'name': item['name'],
        'initial_qty': float(item['initial_qty']), 'lead_time_days': lead,
        'safety_stock': float(item['safety_stock']), 'daily_demand': float(item['daily_demand']),
        'balance': balance, 'effective_in_transit': float(effective or 0),
        'lead_time_demand': lead_demand, 'replenishment_candidate': candidate,
        'horizon_date': horizon,
    }


def _default_scenario(cx) -> dict | None:
    row = cx.execute('select id,name,note,created_at from inventory_scenarios '
                     'order by created_at desc limit 1').fetchone()
    return dict(row) if row else None


def _inventory_via_tables(params) -> tuple[dict, list[dict], dict]:
    """Read-only fallback when the inventory service module is unavailable."""
    with db.connect() as cx:
        scenario = None
        if params.get('scenario_id'):
            row = cx.execute('select id,name,note,created_at from inventory_scenarios where id=?',
                             (params['scenario_id'],)).fetchone()
            scenario = dict(row) if row else None
            if not scenario:
                raise ValueError(f"模拟库存场景 {params['scenario_id']} 不存在")
        else:
            scenario = _default_scenario(cx)
        if not scenario:
            raise ValueError('库存模块未就绪：尚未建立任何模拟库存场景（请先在“模拟库存”页创建场景）')
        item = _inventory_balance(cx, scenario['id'], params['stock_code'])
        if not item:
            raise ValueError(f"模拟库存场景 {scenario['name']} 中没有商品 {params['stock_code']} 的模拟参数")
        item_count = cx.execute('select count(*) from inventory_items where scenario_id=?',
                                (scenario['id'],)).fetchone()[0]
    scenario['item_count'] = int(item_count)
    return scenario, [item], item


