"""AI assistant: declared read-only tool layer, local rule planner and optional LLM.

Security / contract rules enforced here (API contract section 5.7):

* the API key is only read from the server environment (``app.core.config``); it is never
  returned by any response, never written to ``ai_runs`` and never put into a log line
  (all outgoing strings pass through :func:`_redact`).  Non-secret settings
  (``settings.ai``: base_url/model/timeout_seconds, written by ``PUT /api/settings``)
  override the environment defaults via :func:`ai_config`; the key never comes from
  the settings table;
* only the declared tools below can run.  There is no generic SQL/Shell/file tool, no
  arbitrary URL fetch and no write operation;
* every number in an answer comes from a tool result computed by the existing
  ``app.services.analytics.Analytics`` / ``app.services.data.Store`` / ``app.services.forecasting``
  code, or from the read-only public functions of the parallel inventory service
  (``app.services.inventory.items_payload`` etc.); when that module is unavailable the
  inventory tool degrades to a read-only table query with the contract formula and a
  clear "库存模块未就绪" warning instead of raising;
* without a configured key the answer is generated by :func:`_local_answer`, states
  ``未调用大模型，数字来自服务端工具`` and never invents a natural-language conclusion;
* a question that cannot be mapped to a tool returns ``status="need_clarification"``
  with one concrete follow-up question.
"""
